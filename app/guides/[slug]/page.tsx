import Link from "next/link";
import { notFound } from "next/navigation";
import { getGuide, humanChecks } from "@/lib/guides";
import { COMPOSIO_TAIL, type Claim, type ClaimLevel, type VerdictTier } from "@/lib/schema";
import { DifficultyBadge, LEVEL_HELP, LEVEL_LABEL, LevelBadge, OwnerBadge, TrackBadge } from "../../components/badges";
import { ShareButton } from "../../components/ShareButton";

export const dynamic = "force-dynamic";

const LEVELS: ClaimLevel[] = ["tested", "doc-confirmed", "community-reported", "inferred", "unverified"];

function ClaimRefs({ ids, claims }: { ids: string[]; claims: Map<string, Claim> }) {
  if (ids.length === 0) return null;
  return (
    <span className="claim-refs">
      {ids.map((id) => {
        const claim = claims.get(id);
        return (
          <a key={id} href={`#claim-${id}`} className={`claim-ref level-${claim?.level ?? "unverified"}`} title={claim?.text}>
            {id}
          </a>
        );
      })}
    </span>
  );
}

function TierCard({ label, tier }: { label: string; tier: VerdictTier }) {
  return (
    <div className="card tier-card">
      <div className="tier-top">
        <span className="tier-label">{label}</span>
        <DifficultyBadge difficulty={tier.difficulty} />
      </div>
      <p className="tier-headline">{tier.headline}</p>
      <dl className="tier-facts">
        <div>
          <dt>Hands-on</dt>
          <dd>{tier.handsOnTime}</dd>
        </div>
        <div>
          <dt>Waiting</dt>
          <dd>{tier.waitTime}</dd>
        </div>
      </dl>
    </div>
  );
}

export default async function GuidePage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const entry = await getGuide(slug);
  if (!entry) notFound();
  const { guide, handResearched } = entry;
  const claims = new Map(guide.claims.map((c) => [c.id, c]));
  const levelCounts = LEVELS.map((level) => ({ level, count: guide.claims.filter((c) => c.level === level).length }));
  const tail = guide.composioTail ?? [...COMPOSIO_TAIL];
  const checks = humanChecks(guide.slug);
  const corrected = [...checks.values()].filter((c) => c.result === "corrected").length;

  return (
    <article className="guide">
      <nav className="crumbs">
        <Link href="/">Library</Link> / {guide.app}
      </nav>

      <header className="guide-head">
        <div>
          <h1>{guide.app}</h1>
          <div className="guide-meta">
            <TrackBadge track={guide.track} />
            <span className="muted small">
              Composio toolkit <code>{guide.composio.toolkitSlug}</code> <ClaimRefs ids={guide.composio.claimIds} claims={claims} />
            </span>
          </div>
        </div>
        <ShareButton />
      </header>

      <p className={`provenance ${handResearched ? "provenance-ref" : ""}`}>
        {handResearched
          ? "Hand-researched reference guide. Used as the quality bar for generated guides; not produced by the agent."
          : `Generated by ${guide.generationLog?.model ?? guide.generatedBy} on ${guide.generatedAt}, then audited against the same sources.`}
        {checks.size > 0 && (
          <>
            {" "}
            <a href="#evidence">
              A person checked {checks.size} claim{checks.size === 1 ? "" : "s"} against the sources
              {corrected > 0 ? `; ${corrected} needed correcting` : ""}.
            </a>
          </>
        )}
      </p>

      {/* Verdict first */}
      <section className="verdict">
        <p className="summary">{guide.verdict.summary}</p>
        <div className="tier-grid">
          <TierCard label="Prototype" tier={guide.verdict.prototype} />
          <TierCard label="Production" tier={guide.verdict.production} />
        </div>
        <p className="muted small">Confidence: {guide.verdict.confidence}</p>
        <div className="next-action">
          <span className="next-label">Do this next</span>
          <p>{guide.nextAction}</p>
        </div>
      </section>

      <section>
        <h2 className="section-title">What an agent can do, and where you take over</h2>
        <div className="split">
          <div className="card">
            <h3 className="split-title">Agent can do</h3>
            <ul>{guide.agentVsYou.agentCanDo.map((t, i) => <li key={i}>{t}</li>)}</ul>
          </div>
          <div className="card">
            <h3 className="split-title">You must do</h3>
            <ul>{guide.agentVsYou.youMustDo.map((t, i) => <li key={i}>{t}</li>)}</ul>
          </div>
        </div>
      </section>

      <section>
        <h2 className="section-title">Steps</h2>
        <ol className="stages">
          {guide.stages.map((stage, i) => (
            <li key={stage.id} className="stage">
              <div className="stage-num">{i + 1}</div>
              <div className="stage-body">
                <div className="stage-head">
                  <h3>{stage.name}</h3>
                  <OwnerBadge owner={stage.owner} />
                </div>
                <p className="muted small">
                  Effort: {stage.effort}
                  {stage.wait ? ` · Wait: ${stage.wait}` : ""}
                </p>
                <ul>
                  {stage.steps.map((step, j) => (
                    <li key={j}>
                      {step.text} <ClaimRefs ids={step.claimIds} claims={claims} />
                    </li>
                  ))}
                </ul>
              </div>
            </li>
          ))}
          {guide.track === "bring-your-own" && guide.composioTail && (
            <li className="stage">
              <div className="stage-num">{guide.stages.length + 1}</div>
              <div className="stage-body">
                <div className="stage-head">
                  <h3>Connect your app to Composio</h3>
                  <OwnerBadge owner="developer" />
                </div>
                <ol>{tail.map((t, i) => <li key={i}>{t}</li>)}</ol>
              </div>
            </li>
          )}
        </ol>
        {guide.track === "managed" && (
          <details className="card details">
            <summary>Bringing your own OAuth app instead (custom branding, scopes or quota)</summary>
            <ol>{tail.map((t, i) => <li key={i}>{t}</li>)}</ol>
          </details>
        )}
      </section>

      {guide.requirements.length > 0 && (
        <section>
          <h2 className="section-title">Requirements</h2>
          <ul className="card plain-list">{guide.requirements.map((r, i) => <li key={i}>{r}</li>)}</ul>
        </section>
      )}

      {guide.blockers.length > 0 && (
        <section>
          <h2 className="section-title">Blockers and what to do</h2>
          <div className="blockers">
            {guide.blockers.map((b, i) => (
              <div key={i} className="card blocker">
                <h3>
                  {b.issue} <ClaimRefs ids={b.claimIds} claims={claims} />
                </h3>
                <p><strong>When it hits:</strong> {b.whenItHits}</p>
                <p><strong>What to do:</strong> {b.whatToDo}</p>
                {b.escalation && (
                  <p>
                    <strong>Escalate:</strong>{" "}
                    {b.escalation.startsWith("http") ? <a href={b.escalation} target="_blank" rel="noreferrer">{b.escalation}</a> : b.escalation}
                  </p>
                )}
              </div>
            ))}
          </div>
        </section>
      )}

      <section>
        <h2 className="section-title">What was tested, and what is uncertain</h2>
        <div className="split three">
          <div className="card">
            <h3 className="split-title">Tested in this run</h3>
            {guide.tested.length ? <ul>{guide.tested.map((t, i) => <li key={i}>{t}</li>)}</ul> : <p className="muted">Nothing.</p>}
          </div>
          <div className="card">
            <h3 className="split-title">Not tested</h3>
            {guide.notTested.length ? <ul>{guide.notTested.map((t, i) => <li key={i}>{t}</li>)}</ul> : <p className="muted">Nothing listed.</p>}
          </div>
          <div className="card card-warn">
            <h3 className="split-title">Uncertain</h3>
            {guide.uncertain.length ? <ul>{guide.uncertain.map((t, i) => <li key={i}>{t}</li>)}</ul> : <p className="muted">Nothing listed.</p>}
          </div>
        </div>
      </section>

      <section>
        <h2 className="section-title" id="evidence">Evidence ({guide.claims.length} claims)</h2>
        <div className="legend">
          {levelCounts.map(({ level, count }) => (
            <span key={level} title={LEVEL_HELP[level]}>
              <LevelBadge level={level} /> {count}
            </span>
          ))}
        </div>
        <table className="claims">
          <thead>
            <tr>
              <th>ID</th>
              <th>Claim</th>
              <th>Evidence</th>
              <th>Sources</th>
              <th>Human check</th>
            </tr>
          </thead>
          <tbody>
            {guide.claims.map((c) => (
              <tr key={c.id} id={`claim-${c.id}`}>
                <td className="mono">{c.id}</td>
                <td>{c.text}</td>
                <td><LevelBadge level={c.level} /></td>
                <td className="sources">
                  {c.sources.length === 0 && <span className="muted">none</span>}
                  {c.sources.map((s, i) => (
                    <div key={i}>
                      <a href={s.url} target="_blank" rel="noreferrer">{new URL(s.url).hostname + new URL(s.url).pathname}</a>
                      {s.fetchedAt && <span className="muted"> · fetched {s.fetchedAt}</span>}
                      {s.note && <div className="muted small">{s.note}</div>}
                    </div>
                  ))}
                </td>
                <td>
                  {checks.get(c.id) ? (
                    <>
                      <span className={`badge check-${checks.get(c.id)!.result}`}>{checks.get(c.id)!.result.replace("-", " ")}</span>
                      <div className="muted small">{checks.get(c.id)!.note}</div>
                    </>
                  ) : (
                    <span className="muted small">not sampled</span>
                  )}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className="muted small">{LEVELS.map((l) => `${LEVEL_LABEL[l]}: ${LEVEL_HELP[l].toLowerCase()}.`).join(" ")}</p>
      </section>

      {guide.auditLog.length > 0 && (
        <section>
          <h2 className="section-title">Audit log: what the audit changed</h2>
          <div className="audit">
            {guide.auditLog.map((a, i) => (
              <div key={i} className="card audit-row">
                <span className="badge audit-change">{a.change}</span>
                <p><span className="muted">Was:</span> <s>{a.was}</s></p>
                <p><span className="muted">Now:</span> {a.now}</p>
              </div>
            ))}
          </div>
        </section>
      )}
    </article>
  );
}
